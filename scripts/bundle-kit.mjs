// Bundle kit/ into the Worker as src/kit.generated.ts, so skills, the event
// template and the starting kit for a new team ship with every deploy (no git
// clone per call, nothing to push to a separate repo). Also bundles the CRM
// schema (migrations/, minus the access registry) as src/migrations.generated.ts
// for each team's Durable Object. Runs from wrangler's build command and from
// `npm run check`.

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const kit = join(root, "kit");
const DIRS = ["skills", "templates", "brand", "config"];
const SKIP = new Set([".DS_Store"]);
// Who has access stays in the main D1; a team's own database never has these.
const REGISTRY = new Set(["0006_members", "0008_connector_people", "0009_self_serve_members", "0010_member_admins", "0011_teams"]);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    if (SKIP.has(name)) return [];
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const files = {};
for (const d of DIRS) {
  for (const full of walk(join(kit, d)).sort()) {
    files[relative(kit, full).split(sep).join("/")] = readFileSync(full, "utf8");
  }
}

writeFileSync(
  join(root, "src", "kit.generated.ts"),
  `// Generated by scripts/bundle-kit.mjs from kit/. Don't edit; edit kit/ and rebuild.\n` +
    `export const KIT: Record<string, string> = ${JSON.stringify(files, null, 1)};\n`,
);
console.log(`bundle-kit: ${Object.keys(files).length} files from kit/${DIRS.join(", kit/")}`);

const migrations = readdirSync(join(root, "migrations"))
  .filter((f) => f.endsWith(".sql") && !REGISTRY.has(f.slice(0, -4)))
  .sort()
  .map((f) => [f.slice(0, -4), readFileSync(join(root, "migrations", f), "utf8")]);

writeFileSync(
  join(root, "src", "migrations.generated.ts"),
  `// Generated by scripts/bundle-kit.mjs from migrations/ (the CRM schema, without the access registry). Don't edit.\n` +
    `export const MIGRATIONS: [name: string, sql: string][] = ${JSON.stringify(migrations, null, 1)};\n`,
);
console.log(`bundle-kit: ${migrations.length} CRM migrations for team databases`);
